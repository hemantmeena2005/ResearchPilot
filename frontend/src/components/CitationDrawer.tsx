import React from 'react';
import type { CitationItem } from '../types';
import { BookOpen, FileText, ShieldCheck } from 'lucide-react';

interface CitationDrawerProps {
  citations: CitationItem[];
  selectedCitation: CitationItem | null;
  onSelectCitation: (citation: CitationItem | null) => void;
}

export const CitationDrawer: React.FC<CitationDrawerProps> = ({
  citations,
  selectedCitation,
  onSelectCitation,
}) => {
  if (citations.length === 0) {
    return (
      <div className="w-80 border-l border-slate-800 bg-[#0d1322]/80 p-5 flex flex-col items-center justify-center text-center text-slate-500">
        <BookOpen className="w-8 h-8 mb-3 text-slate-600 stroke-[1.5]" />
        <p className="text-sm font-medium text-slate-400">Evidence Grounding</p>
        <p className="text-xs mt-1 text-slate-500 leading-relaxed">
          Substantive claims generated by ResearchPilot are grounded in extracted excerpts with page references.
        </p>
      </div>
    );
  }

  return (
    <div className="w-88 border-l border-slate-800 bg-[#0d1322] flex flex-col h-full overflow-hidden">
      <div className="p-4 border-b border-slate-800 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <ShieldCheck className="w-4 h-4 text-emerald-400" />
          <h3 className="text-sm font-semibold text-slate-200">
            Retrieved Evidence ({citations.length})
          </h3>
        </div>
        <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-emerald-950/60 text-emerald-400 border border-emerald-800/50">
          Verified
        </span>
      </div>

      <div className="flex-1 overflow-y-auto p-4 space-y-3">
        {citations.map((cite, idx) => {
          const isSelected = selectedCitation?.chunk_id === cite.chunk_id;
          return (
            <div
              key={cite.chunk_id || idx}
              onClick={() => onSelectCitation(isSelected ? null : cite)}
              className={`p-3.5 rounded-xl border text-xs cursor-pointer transition-all ${
                isSelected
                  ? 'border-blue-500/80 bg-blue-950/30 shadow-md shadow-blue-900/20 ring-1 ring-blue-500/40'
                  : 'border-slate-800/80 bg-slate-900/50 hover:border-slate-700 hover:bg-slate-800/40'
              }`}
            >
              <div className="flex items-start justify-between gap-2 mb-2">
                <span className="inline-flex items-center gap-1.5 font-semibold text-blue-400">
                  <span className="w-4 h-4 rounded-full bg-blue-500/20 text-blue-300 flex items-center justify-center text-[10px]">
                    {idx + 1}
                  </span>
                  Page {cite.page_number}
                </span>
                {cite.relevance_score !== undefined && cite.relevance_score !== null && (
                  <span className="text-[10px] text-slate-400 font-mono">
                    score: {cite.relevance_score.toFixed(3)}
                  </span>
                )}
              </div>

              <div className="text-slate-300 font-medium mb-1.5 line-clamp-1 flex items-center gap-1">
                <FileText className="w-3 h-3 text-slate-400 shrink-0" />
                <span>{cite.document_title || cite.filename}</span>
              </div>

              <p className="text-slate-400 leading-relaxed italic bg-slate-950/40 p-2.5 rounded-lg border border-slate-800/60 font-serif">
                "{cite.excerpt}"
              </p>

              {cite.claim_association && (
                <div className="mt-2 text-[11px] text-slate-500 flex items-center gap-1">
                  <span>Target: {cite.claim_association}</span>
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
};
